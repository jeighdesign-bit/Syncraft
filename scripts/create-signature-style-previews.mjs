import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import sharp from 'sharp';
import { LOGO_STYLES } from '../src/lib/logoStudio.mjs';
import { createLogoStylePreviewAssets } from './lib/logoStylePreviewAssets.mjs';

const assetDirectory = 'public/images/logo-styles';
const outputDirectory = 'outputs/style-preview-refresh';
const assets = Object.entries(createLogoStylePreviewAssets());
const styleNames = new Map(LOGO_STYLES.map(style => [style.id, style.name]));
mkdirSync(assetDirectory, { recursive: true });
mkdirSync(outputDirectory, { recursive: true });
for (const [id, svg] of assets) writeFileSync(`${assetDirectory}/${id}-signature.svg`, svg);

// Content-based versions prevent stale artwork without manual JSX counters.
const customStyles = new Set(assets.map(([id]) => id));
const previews = Object.fromEntries(LOGO_STYLES.map(({ id }) => {
  const filename = id === 'streetwear-lettering'
    ? 'streetwear-sonder-transparent.png'
    : customStyles.has(id) ? `${id}-signature.svg` : `${id}.webp`;
  const version = createHash('sha256')
    .update(readFileSync(`${assetDirectory}/${filename}`)).digest('hex').slice(0, 12);
  return [id, `/images/logo-styles/${filename}?v=${version}`];
}));
writeFileSync('src/lib/logoStylePreviews.mjs', [
  '// Generated by scripts/create-signature-style-previews.mjs. Do not edit by hand.',
  `export const LOGO_STYLE_PREVIEWS = Object.freeze(${JSON.stringify(previews, null, 2)});`,
  '',
].join('\n'));

const layers = [];
const cards = [];
const columns = 4;
const width = 740;
const height = 20 + Math.ceil(assets.length / columns) * 210;
for (const [index, [id, svg]] of assets.entries()) {
  const x = 20 + (index % columns) * 180;
  const y = 20 + Math.floor(index / columns) * 210;
  layers.push({ input: await sharp(Buffer.from(svg)).resize(128, 128).png().toBuffer(), left: x + 26, top: y + 16 });
  cards.push(`<rect x="${x}" y="${y}" width="164" height="192" rx="12" fill="#202023" stroke="#3c3c40"/><text x="${x + 82}" y="${y + 171}" font-size="15" text-anchor="middle">${styleNames.get(id)}</text>`);
}
const grid = Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}"><rect width="${width}" height="${height}" fill="#19191c"/><g font-family="Arial,sans-serif" fill="#ddd6ea">${cards.join('')}</g></svg>`);
await sharp(grid).composite(layers).png().toFile(`${outputDirectory}/preview.png`);

// True-size rendering matches the 48px previews displayed in Studio.
const thumbnails = await Promise.all(assets.map(async ([, svg], index) => ({
  input: await sharp(Buffer.from(svg)).resize(48, 48).png().toBuffer(),
  left: 12 + index * 60,
  top: 12,
})));
await sharp({ create: { width: 24 + assets.length * 60, height: 72, channels: 4, background: '#202023' } })
  .composite(thumbnails).png().toFile(`${outputDirectory}/at-48px.png`);
console.log(`Saved ${assets.length} previews, content-based cache versions and review sheets.`);
